package com.zextras.carbonio.files.it;

import com.zextras.carbonio.files.FilesStackTestResource;
import com.zextras.carbonio.files.TestUtils;
import com.zextras.carbonio.files.api.utilities.GraphqlCommandBuilder;
import com.zextras.carbonio.files.dal.dao.ebean.ACL;
import com.zextras.carbonio.files.it.support.AbstractFilesIT;
import io.restassured.response.Response;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.List;
import java.util.Map;
import org.assertj.core.api.Assertions;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

/**
 * Several notifications for the same user generated by a single request must each increment the
 * unread counter, both as reported by {@code getNotifications} and as stored in {@code
 * user_notifications_info}.
 */
class NotificationUnreadCounterApiIT extends AbstractFilesIT {

  private static final String REQUESTER_ID = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa";
  private static final String SECOND_USER_ID = "bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb";
  private static final String REQUESTER_COOKIE = "ZM_AUTH_TOKEN=fake-token";
  private static final String SECOND_USER_COOKIE = "ZM_AUTH_TOKEN=fake-token-b";

  @BeforeAll
  static void registerUsers() {
    FilesStackTestResource.getUserManagementService().registerToken("fake-token", REQUESTER_ID);
    FilesStackTestResource.getUserManagementService().registerToken("fake-token-b", SECOND_USER_ID);
  }

  private static Map<String, Object> getNotifications(boolean updateLastSeen, String cookie) {
    String query =
        GraphqlCommandBuilder.aQueryBuilder("getNotifications")
            .withBoolean("update_last_seen", updateLastSeen)
            .withWantedResultFormat("{ notifications { ... on RemovedNode { id } }, unread }")
            .build();
    Response response = graphql(query, cookie);
    Assertions.assertThat(response.getStatusCode()).isEqualTo(200);
    return TestUtils.jsonResponseToMap(response.getBody().asString(), "getNotifications");
  }

  private static int storedUnread(String userId) throws SQLException {
    try (Connection connection = jdbcConnection();
        PreparedStatement statement =
            connection.prepareStatement(
                "SELECT unread FROM user_notifications_info WHERE user_id = ?")) {
      statement.setString(1, userId);
      try (ResultSet resultSet = statement.executeQuery()) {
        Assertions.assertThat(resultSet.next()).isTrue();
        return resultSet.getInt(1);
      }
    }
  }

  @Test
  void givenTwoNodesTrashedInOneRequestTheUnreadCounterOfTheSharedUserIsIncrementedTwice()
      throws SQLException {
    // Given
    String folderId = seedFolder("folder", LOCAL_ROOT, REQUESTER_COOKIE);
    String firstFileId =
        seedFile("first.txt", folderId, "one".getBytes(StandardCharsets.UTF_8), REQUESTER_COOKIE);
    String secondFileId =
        seedFile("second.txt", folderId, "two".getBytes(StandardCharsets.UTF_8), REQUESTER_COOKIE);
    seedShare(folderId, SECOND_USER_ID, ACL.SharePermission.READ_AND_WRITE, REQUESTER_COOKIE);
    getNotifications(true, SECOND_USER_COOKIE);
    Assertions.assertThat(storedUnread(SECOND_USER_ID)).isZero();

    // When
    String mutation =
        GraphqlCommandBuilder.aMutationBuilder("trashNodes")
            .withListOfStrings("node_ids", new String[] {firstFileId, secondFileId})
            .withWantedResultFormat("")
            .build();
    Response response = graphql(mutation, REQUESTER_COOKIE);
    Assertions.assertThat(TestUtils.jsonResponseToErrors(response.getBody().asString())).isEmpty();

    // Then
    Map<String, Object> page = getNotifications(false, SECOND_USER_COOKIE);
    @SuppressWarnings("unchecked")
    List<Map<String, Object>> notifications = (List<Map<String, Object>>) page.get("notifications");
    Assertions.assertThat(notifications).filteredOn(n -> n.containsKey("id")).hasSize(2);
    Assertions.assertThat(page).containsEntry("unread", 2);
    Assertions.assertThat(storedUnread(SECOND_USER_ID)).isEqualTo(2);
  }
}
